def version_announcement() -> str:
    notes = RELEASE_NOTES.get(__version__, ("例行更新與穩定性調整。",))
    lines = "\n".join(f"- {note}" for note in notes)
    return f"墨雪已更新到 v{__version__} 了喵。\n{lines}\n\n之後也請多多指教喵。"
